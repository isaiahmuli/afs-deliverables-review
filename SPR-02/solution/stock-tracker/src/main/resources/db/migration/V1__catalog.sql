-- V1: the catalog. Products, categories, and the join table between them.
CREATE TABLE product (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(200) NOT NULL,
    quantity integer      NOT NULL DEFAULT 0 CHECK (quantity >= 0)
);
CREATE UNIQUE INDEX product_name_uq ON product (lower(name));

CREATE TABLE category (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL
);
CREATE UNIQUE INDEX category_name_uq ON category (lower(name));

-- Many-to-many: a product can be in several categories, a category holds several products.
CREATE TABLE product_category (
    product_id  bigint NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    category_id bigint NOT NULL REFERENCES category (id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, category_id)
);
CREATE INDEX product_category_category_idx ON product_category (category_id);
