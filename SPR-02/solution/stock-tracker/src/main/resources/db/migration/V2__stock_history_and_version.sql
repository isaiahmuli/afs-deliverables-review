-- V2: stock history and optimistic locking. Existing products are kept (version starts at 0).
ALTER TABLE product ADD COLUMN version bigint NOT NULL DEFAULT 0;

-- One-to-many: each product has many adjustments, its history.
CREATE TABLE stock_adjustment (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      bigint       NOT NULL REFERENCES product (id),
    quantity_change integer      NOT NULL CHECK (quantity_change <> 0),
    quantity_after  integer      NOT NULL CHECK (quantity_after >= 0),
    reason          varchar(500) NOT NULL CHECK (btrim(reason) <> ''),
    adjusted_at     timestamptz  NOT NULL
);
CREATE INDEX stock_adjustment_product_idx ON stock_adjustment (product_id, adjusted_at, id);
